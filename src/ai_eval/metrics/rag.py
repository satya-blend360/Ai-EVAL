from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from ai_eval.utils.llm import LLMProvider
from ai_eval.models import RAGMetrics
from ai_eval.utils.logger import logger

# Pydantic schemas for LLM-as-a-judge outputs

class RelevancyScore(BaseModel):
    score: float = Field(..., description="Relevancy score between 0.0 and 1.0")
    reasoning: str = Field(..., description="Detailed explanation of the score")

class FaithfulnessStatement(BaseModel):
    statement: str
    is_supported: bool
    reason: str

class FaithfulnessReport(BaseModel):
    statements: List[FaithfulnessStatement]
    score: float = Field(..., description="Fraction of statements supported by context (0.0 to 1.0)")

class ContextRecallStatement(BaseModel):
    statement: str
    in_context: bool
    reason: str

class ContextRecallReport(BaseModel):
    statements: List[ContextRecallStatement]
    score: float = Field(..., description="Fraction of ground truth statements found in context (0.0 to 1.0)")

class ContextPrecisionBlock(BaseModel):
    block_index: int
    is_relevant: bool
    reason: str

class ContextPrecisionReport(BaseModel):
    blocks: List[ContextPrecisionBlock]
    score: float = Field(..., description="Calculated precision score (0.0 to 1.0)")

class RAGEvaluator:
    """Evaluates RAG quality metrics (Context Precision, Context Recall, Faithfulness, Relevancy, Groundedness)."""

    def __init__(self, llm_provider: Optional[LLMProvider] = None):
        self.llm_provider = llm_provider or LLMProvider()

    def evaluate(
        self,
        query: str,
        contexts: List[str],
        generated_answer: str,
        ground_truth_answer: Optional[str] = None
    ) -> RAGMetrics:
        """
        Runs RAG evaluation.
        
        Args:
            query: The user prompt / question
            contexts: List of retrieved text context snippets
            generated_answer: The answer generated by the RAG system
            ground_truth_answer: Optional reference/ideal answer for Context Recall
        """
        logger.info("Starting RAG Metrics Evaluation...")
        
        # 1. Evaluate Faithfulness
        faithfulness_score = self.evaluate_faithfulness(generated_answer, contexts)
        
        # 2. Evaluate Answer Relevancy
        relevancy_score = self.evaluate_answer_relevancy(query, generated_answer)
        
        # 3. Evaluate Groundedness
        # Groundedness is often identical to faithfulness, or defined as ratio of grounded sentences.
        # We will calculate it based on a custom LLM score or let it match faithfulness with a small variance.
        groundedness_score = self.evaluate_groundedness(generated_answer, contexts)
        
        # 4. Evaluate Context Precision
        context_precision = self.evaluate_context_precision(query, contexts)
        
        # 5. Evaluate Context Recall
        context_recall = 1.0  # Default to 1.0 if no ground truth answer is provided
        if ground_truth_answer:
            context_recall = self.evaluate_context_recall(ground_truth_answer, contexts)
            
        return RAGMetrics(
            context_precision=round(context_precision, 4),
            context_recall=round(context_recall, 4),
            faithfulness=round(faithfulness_score, 4),
            answer_relevancy=round(relevancy_score, 4),
            groundedness=round(groundedness_score, 4)
        )

    def evaluate_faithfulness(self, answer: str, contexts: List[str]) -> float:
        """Measures if the generated answer is factually consistent with the retrieved context."""
        if not contexts or not answer:
            return 0.0
            
        context_text = "\n\n".join(contexts)
        
        system_prompt = (
            "You are a Factual Consistency Auditor.\n"
            "Your task is to extract individual statements from the generated answer, "
            "and verify whether each statement is fully supported by the retrieved context.\n"
            "If a statement contains claims not mentioned in the context, mark is_supported as false."
        )
        
        user_prompt = (
            f"Retrieved Context:\n{context_text}\n\n"
            f"Generated Answer:\n{answer}\n\n"
            "Break down the answer into distinct claims, check if each claim is supported by the context, "
            "and calculate the final faithfulness score as: (supported claims / total claims)."
        )
        
        try:
            report, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=FaithfulnessReport
            )
            return report.score
        except Exception as e:
            logger.error(f"Faithfulness evaluation failed: {e}")
            return 0.0

    def evaluate_answer_relevancy(self, query: str, answer: str) -> float:
        """Measures how directly the answer addresses the query without fluff or irrelevant info."""
        if not query or not answer:
            return 0.0
            
        system_prompt = (
            "You are an Answer Relevancy Evaluator.\n"
            "Your task is to judge whether the generated answer is relevant to the user's query.\n"
            "Evaluate if the answer directly addresses the core question, if it is complete, "
            "and if it contains unnecessary padding, repetitions, or irrelevant details.\n"
            "Score from 0.0 (totally irrelevant/fluff) to 1.0 (perfectly relevant and concise)."
        )
        
        user_prompt = (
            f"User Query: {query}\n\n"
            f"Generated Answer:\n{answer}\n\n"
            "Provide a score and your reasoning."
        )
        
        try:
            report, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=RelevancyScore
            )
            return report.score
        except Exception as e:
            logger.error(f"Answer relevancy evaluation failed: {e}")
            return 0.0

    def evaluate_groundedness(self, answer: str, contexts: List[str]) -> float:
        """Measures the extent to which the claims made in the answer can be traced to the context."""
        # Using a direct groundedness scorer
        if not contexts or not answer:
            return 0.0
            
        context_text = "\n\n".join(contexts)
        
        system_prompt = (
            "You are a Groundedness Evaluator.\n"
            "Verify the degree to which the generated response is grounded in and derived from the provided context.\n"
            "Rate the answer on a scale from 0.0 (completely ungrounded/fabricated) to 1.0 (perfectly grounded in facts from context)."
        )
        
        user_prompt = (
            f"Context:\n{context_text}\n\n"
            f"Answer:\n{answer}\n\n"
            "Provide a groundedness score and detailed explanation."
        )
        
        try:
            report, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=RelevancyScore
            )
            return report.score
        except Exception as e:
            logger.error(f"Groundedness evaluation failed: {e}")
            return 0.0

    def evaluate_context_precision(self, query: str, contexts: List[str]) -> float:
        """Measures whether the retrieved context snippets are relevant to the query."""
        if not contexts:
            return 0.0
            
        system_prompt = (
            "You are a Context Precision Auditor.\n"
            "Your task is to analyze each context snippet and decide if it is relevant to answering the user query.\n"
            "Rate each block with a boolean is_relevant and provide a brief reason."
        )
        
        context_blocks = "\n".join([f"Snippet {idx}: {ctx[:200]}..." for idx, ctx in enumerate(contexts)])
        user_prompt = (
            f"User Query: {query}\n\n"
            f"Retrieved Snippets:\n{context_blocks}\n\n"
            "Evaluate each snippet's relevance, and calculate the overall precision score as the fraction of relevant snippets."
        )
        
        try:
            report, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=ContextPrecisionReport
            )
            return report.score
        except Exception as e:
            logger.error(f"Context precision evaluation failed: {e}")
            return 0.0

    def evaluate_context_recall(self, ground_truth: str, contexts: List[str]) -> float:
        """Measures if the retrieved context contains all the facts in the ground truth answer."""
        if not contexts or not ground_truth:
            return 0.0
            
        context_text = "\n\n".join(contexts)
        
        system_prompt = (
            "You are a Context Recall Auditor.\n"
            "Your task is to extract core factual statements from the ground truth reference answer, "
            "and verify whether each statement can be found in the retrieved context.\n"
            "Provide a score as the fraction of ground truth statements present in the context."
        )
        
        user_prompt = (
            f"Ground Truth Answer:\n{ground_truth}\n\n"
            f"Retrieved Context:\n{context_text}\n\n"
            "Perform statement verification and calculate the final context recall score."
        )
        
        try:
            report, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=ContextRecallReport
            )
            return report.score
        except Exception as e:
            logger.error(f"Context recall evaluation failed: {e}")
            return 0.0
