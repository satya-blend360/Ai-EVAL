from typing import List, Dict, Any, Optional
from ai_eval.utils.llm import LLMProvider
from ai_eval.models import HallucinationMetrics, ClaimDetail
from ai_eval.utils.logger import logger

class HallucinationEvaluator:
    """Detects hallucinations by comparing generated answer claims to retrieved evidence."""

    def __init__(self, llm_provider: Optional[LLMProvider] = None):
        self.llm_provider = llm_provider or LLMProvider()

    def evaluate(
        self,
        generated_answer: str,
        evidence_texts: List[str]
    ) -> HallucinationMetrics:
        """
        Runs hallucination detection.
        
        Args:
            generated_answer: The answer generated by the system
            evidence_texts: List of context blocks/documents retrieved as evidence
        """
        logger.info("Starting Hallucination Detection...")
        
        if not generated_answer:
            logger.warning("Empty generated answer. Returning zero claims.")
            return HallucinationMetrics(supported_claims=0, total_claims=0, hallucination_rate=0.0, claims=[])
            
        if not evidence_texts:
            logger.warning("No evidence texts provided. All claims will be unsupported (100% hallucination).")
            # Extract claims first to give a meaningful output, then mark them unsupported.
            claims = self._extract_claims_only(generated_answer)
            claim_details = [
                ClaimDetail(claim=c, is_supported=False, evidence=None, reasoning="No evidence texts provided to verify this claim.")
                for c in claims
            ]
            return HallucinationMetrics(
                supported_claims=0,
                total_claims=len(claims),
                hallucination_rate=100.0 if claims else 0.0,
                claims=claim_details
            )

        evidence_combined = "\n\n".join([f"Evidence [{idx}]: {text}" for idx, text in enumerate(evidence_texts)])

        # Call LLM to extract claims and verify them against evidence in one structured call
        system_prompt = (
            "You are an expert Hallucination Auditor.\n"
            "Your job is to identify all specific factual claims (dates, names, metrics, assertions, features) "
            "made in a generated answer, and verify if each claim is supported by the provided evidence.\n"
            "Be very strict: if a claim is not explicitly mentioned or directly logical to infer from the evidence, "
            "it is NOT supported (meaning it is a hallucination). Make sure to separate claims into small, atomic assertions."
        )

        user_prompt = (
            f"Evidence:\n{evidence_combined}\n\n"
            f"Generated Answer:\n{generated_answer}\n\n"
            "Instructions:\n"
            "1. Extract all factual statements/claims from the Generated Answer.\n"
            "2. For each claim, check if the Evidence supports it.\n"
            "3. State the evidence section that supports it, or state 'None' if unsupported.\n"
            "4. Return the results in a structured format."
        )

        try:
            result, _ = self.llm_provider.call_structured(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
                response_model=HallucinationMetrics
            )
            
            # Recalculate hallucination rate to ensure math consistency
            total = len(result.claims)
            supported = sum(1 for c in result.claims if c.is_supported)
            rate = ((total - supported) / total * 100) if total > 0 else 0.0
            
            return HallucinationMetrics(
                supported_claims=supported,
                total_claims=total,
                hallucination_rate=round(rate, 2),
                claims=result.claims
            )
            
        except Exception as e:
            logger.error(f"Hallucination detection failed: {e}")
            # Fallback
            return HallucinationMetrics(
                supported_claims=0,
                total_claims=0,
                hallucination_rate=0.0,
                claims=[]
            )

    def _extract_claims_only(self, text: str) -> List[str]:
        """Simple fallback to extract claims in case of failure."""
        class ClaimsList(BaseModel):
            claims: List[str]

        system_prompt = "Extract atomic factual claims from the text. Return a JSON list of strings."
        user_prompt = f"Text:\n{text}"
        try:
            res, _ = self.llm_provider.call_structured(system_prompt, user_prompt, ClaimsList)
            return res.claims
        except Exception:
            # splitting by period as emergency fallback
            return [c.strip() for c in text.split('.') if len(c.strip()) > 10]
